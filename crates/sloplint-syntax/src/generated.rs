//! Generated-file detection: a marker inside a comment of the file header.
//! A marker anywhere in a header comment counts, even in license prose.

const WINDOW: usize = 2048;

const MARKERS: [&[u8]; 7] = [
    b"@generated",
    b"automatically generated",
    b"auto generated",
    b"auto-generated",
    b"autogenerated",
    b"do not edit",
    b"do not modify by hand",
];

const BOM: &[u8] = b"\xEF\xBB\xBF";

const COMMENT_LEADERS: [&[u8]; 6] = [b"//", b"/*", b"(*", b"<#", b"\"\"\"", b"'''"];

const BLOCKS: [(&[u8], &[u8]); 5] = [
    (b"/*", b"*/"),
    (b"(*", b"*)"),
    (b"<#", b"#>"),
    (b"\"\"\"", b"\"\"\""),
    (b"'''", b"'''"),
];

enum Header {
    Marked,
    Ended,
    Continues(Option<&'static [u8]>),
}

/// True when a header comment in the first 2048 bytes carries a generated-file marker, in any letter case.
pub fn is_generated(bytes: &[u8]) -> bool {
    let text = if bytes.len() >= BOM.len() && &bytes[..BOM.len()] == BOM {
        &bytes[BOM.len()..]
    } else {
        bytes
    };
    let head = if text.len() > WINDOW {
        &text[..WINDOW]
    } else {
        text
    };
    let (opener, body) = split_opener(head);
    let mut closer = match scan_line(opener, None) {
        Header::Marked => return true,
        Header::Ended => None,
        Header::Continues(open) => open,
    };
    for line in body.split(|byte| *byte == b'\n') {
        match scan_line(line, closer) {
            Header::Marked => return true,
            Header::Ended => return false,
            Header::Continues(open) => closer = open,
        }
    }
    false
}

fn scan_line(line: &[u8], mut closer: Option<&'static [u8]>) -> Header {
    let mut rest = line.trim_ascii_start();
    loop {
        let entered = closer.map_or_else(|| enter_comment(rest), |end| Some((rest, Some(end))));
        let Some((body, end)) = entered else {
            return Header::Ended;
        };
        let (comment, after) = end
            .and_then(|end| split_at(body, end))
            .map_or((body, None), |(comment, after)| (comment, Some(after)));
        if carries_marker(comment) {
            return Header::Marked;
        }
        let Some(after) = after else {
            return Header::Continues(end);
        };
        closer = None;
        rest = after.trim_ascii_start();
    }
}

fn enter_comment(line: &[u8]) -> Option<(&[u8], Option<&'static [u8]>)> {
    if !is_header(line) {
        return None;
    }
    let block = BLOCKS
        .iter()
        .find_map(|(open, close)| Some((line.strip_prefix(*open)?, Some(*close))));
    Some(block.unwrap_or((line, None)))
}

fn split_opener(head: &[u8]) -> (&[u8], &[u8]) {
    if !head.starts_with(b"<?") {
        return (&[], head);
    }
    let (line, body) = head
        .iter()
        .position(|byte| *byte == b'\n')
        .map_or((head, &[][..]), |end| (&head[..end], &head[end + 1..]));
    let after_tag = line
        .iter()
        .position(u8::is_ascii_whitespace)
        .map_or(&[][..], |end| &line[end..]);
    (after_tag, body)
}

fn is_header(line: &[u8]) -> bool {
    if line.is_empty() || is_hash_comment(line) {
        return true;
    }
    COMMENT_LEADERS
        .iter()
        .any(|leader| line.starts_with(leader))
}

fn is_hash_comment(line: &[u8]) -> bool {
    let Some(rest) = line.strip_prefix(b"#") else {
        return false;
    };
    match rest.first() {
        None | Some(b' ' | b'\t' | b'#' | b'\'' | b'-' | b'\r') => true,
        Some(b'!') => matches!(rest.get(1), Some(b'/' | b' ')),
        Some(_) => false,
    }
}

fn carries_marker(line: &[u8]) -> bool {
    MARKERS.iter().any(|marker| {
        line.windows(marker.len())
            .any(|window| window.eq_ignore_ascii_case(marker))
    })
}

fn split_at<'a>(haystack: &'a [u8], needle: &[u8]) -> Option<(&'a [u8], &'a [u8])> {
    let at = haystack
        .windows(needle.len())
        .position(|window| window == needle)?;
    Some((&haystack[..at], &haystack[at + needle.len()..]))
}

#[cfg(test)]
mod tests {
    use super::is_generated;

    #[test]
    fn markers_on_comment_lines_match_in_any_letter_case() {
        for head in [
            &b"// @generated\nfn f() {}\n"[..],
            b"// @GENERATED\nfn f() {}\n",
            b"  // AUTOMATICALLY GENERATED\nfn f() {}\n",
            b"// Code generated by tool. DO NOT EDIT.\nfn f() {}\n",
            b"# Auto generated by tools/make_width_tables.py\nX = 1\n",
            b"/* Autogenerated */\nint x;\n",
            b"/*\n * auto-generated file\n */\nint x;\n",
            b"(* do not edit *)\nlet x = 1\n",
            b"\"\"\"Autogenerated module.\"\"\"\nX = 1\n",
            b"\xEF\xBB\xBF// @generated\nclass C {}\n",
            b"// GENERATED CODE - DO NOT MODIFY BY HAND\npart of 'a.dart';\n",
        ] {
            assert!(is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn markers_in_code_or_strings_do_not_count() {
        for head in [
            &b"HEADER = \"# Auto generated by this tool\"\n"[..],
            b"const MARKERS: [&str; 1] = [\"do not edit\"];\n",
            b"print('@generated')\n",
            b"// Code generated by hand.\nfn f() {}\n",
            b"fn f() {}\n",
            b"",
        ] {
            assert!(!is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn marker_after_first_code_line_does_not_count() {
        for head in [
            &b"fn f() {}\n// @generated\n"[..],
            b"x = 1\n# auto-generated\n",
            b"package main\n// Code generated by protoc-gen-go. DO NOT EDIT.\n",
            b"<?php\n$x = 1;\n// @generated\n",
            b"// license\nfn f() {}\n// Callers must not edit: do not edit the returned slice\n",
            b"#include <stdio.h>\n// Do not edit below\nint x;\n",
            b"#![allow(dead_code)]\n// do not edit the table by hand\nfn f() {}\n",
            b"// see src/*.go\npackage x\n// @generated\n",
            b"*a, b = range(3)\n# @generated\nX = 1\n",
            b"<?xml version=\"1.0\"?><!-- do not edit -->\n<a/>\n",
        ] {
            assert!(!is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn marker_in_code_after_a_block_closer_does_not_count() {
        for head in [
            &b"/* license */ const HELP: &str = \"do not edit\";\n"[..],
            b"/*\n * license\n */ const HELP: &str = \"do not edit\";\n",
            b"(* license *) let help = \"auto-generated\"\n",
            b"\"\"\"Docs.\"\"\"; HELP = \"do not edit\"\n",
            b"<?php /* license\n */ $x = \"do not edit\";\n",
        ] {
            assert!(!is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn marker_in_a_comment_after_a_block_closer_counts() {
        for head in [
            &b"/* license */ // @generated\nfn f() {}\n"[..],
            b"/*\n * license\n */ /* do not edit */\nint x;\n",
        ] {
            assert!(is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn marker_in_header_counts() {
        for head in [
            &b"// @generated\nfn f() {}\n"[..],
            b"# auto-generated\nx = 1\n",
            b"/*\nauto-generated file\n*/\nint x;\n",
            b"(*\nauto-generated\n*)\nlet x = 1\n",
            b"\"\"\"\nauto-generated docs\n\"\"\"\nX = 1\n",
            b"<?php\n// @generated\n$x = 1;\n",
            b"\xEF\xBB\xBF# @generated\nx = 1\n",
            b"#!/usr/bin/env python\n# auto-generated\nx = 1\n",
            b"# frozen_string_literal: true\n#\n## auto-generated\nX = 1\n",
            b"#-*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
            b"#' @generated\nx <- 1\n",
            b"<?php /* @generated */\n$x = 1;\n",
            b"<?php // @generated\n$x = 1;\n",
            b"<?php declare(strict_types=1);\n// @generated\n$x = 1;\n",
            b"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n",
        ] {
            assert!(is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn a_marker_past_the_window_does_not_count() {
        let mut far = b"// ".to_vec();
        far.extend(vec![b'x'; 2048]);
        far.extend_from_slice(b"\n// do not edit\n");
        assert!(!is_generated(&far));
        let mut near = b"// ".to_vec();
        near.extend(vec![b'x'; 1024]);
        near.extend_from_slice(b"\n// do not edit\n");
        assert!(is_generated(&near));
    }

    #[test]
    fn unterminated_block_at_window_end_does_not_panic() {
        let mut open_only = b"/*\n".to_vec();
        open_only.extend(vec![b'x'; 2048]);
        assert!(!is_generated(&open_only));
        let mut open_marker = b"/* do not edit\n".to_vec();
        open_marker.extend(vec![b'x'; 2048]);
        assert!(is_generated(&open_marker));
    }
}
