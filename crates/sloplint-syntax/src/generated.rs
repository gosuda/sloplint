//! Generated-file detection: a marker on a comment line in the file header.
//! A marker anywhere in the header counts, even in license prose.

const WINDOW: usize = 2048;

const MARKERS: [&[u8]; 7] = [
    b"@generated",
    b"automatically generated",
    b"auto generated",
    b"auto-generated",
    b"autogenerated",
    b"do not edit",
    b"do not modify by hand",
];

const BOM: &[u8] = b"\xEF\xBB\xBF";

const COMMENT_LEADERS: [&[u8]; 8] = [b"//", b"/*", b"*", b"#", b"(*", b"<#", b"\"\"\"", b"'''"];

const BLOCKS: [(&[u8], &[u8]); 5] = [
    (b"/*", b"*/"),
    (b"(*", b"*)"),
    (b"<#", b"#>"),
    (b"\"\"\"", b"\"\"\""),
    (b"'''", b"'''"),
];

/// True when a header line in the first 2048 bytes carries a generated-file marker, in any letter case.
pub fn is_generated(bytes: &[u8]) -> bool {
    let text = if bytes.len() >= BOM.len() && &bytes[..BOM.len()] == BOM {
        &bytes[BOM.len()..]
    } else {
        bytes
    };
    let head = if text.len() > WINDOW {
        &text[..WINDOW]
    } else {
        text
    };
    let mut closer: Option<&[u8]> = None;
    let mut first = true;
    for line in head.split(|byte| *byte == b'\n') {
        let trimmed = line.trim_ascii_start();
        if let Some(end) = closer {
            if carries_marker(trimmed) {
                return true;
            }
            if contains(trimmed, end) {
                closer = None;
            }
        } else if is_header(trimmed, first) {
            if carries_marker(trimmed) {
                return true;
            }
            closer = unclosed_block(trimmed);
        } else {
            break;
        }
        first = false;
    }
    false
}

fn is_header(line: &[u8], first: bool) -> bool {
    if first && line.starts_with(b"<?") {
        return true;
    }
    if line.is_empty() {
        return true;
    }
    COMMENT_LEADERS
        .iter()
        .any(|leader| line.starts_with(leader))
}

fn carries_marker(line: &[u8]) -> bool {
    MARKERS.iter().any(|marker| {
        line.windows(marker.len())
            .any(|window| window.eq_ignore_ascii_case(marker))
    })
}

fn contains(haystack: &[u8], needle: &[u8]) -> bool {
    if needle.is_empty() || haystack.len() < needle.len() {
        return false;
    }
    haystack.windows(needle.len()).any(|w| w == needle)
}

fn unclosed_block(line: &[u8]) -> Option<&'static [u8]> {
    for (open, close) in BLOCKS {
        if opens_without_close(line, open, close) {
            return Some(close);
        }
    }
    None
}

fn opens_without_close(line: &[u8], open: &[u8], close: &[u8]) -> bool {
    let mut i = 0;
    while i + open.len() <= line.len() {
        if &line[i..i + open.len()] == open {
            return !contains(&line[i + open.len()..], close);
        }
        i += 1;
    }
    false
}

#[cfg(test)]
mod tests {
    use super::is_generated;

    #[test]
    fn markers_on_comment_lines_match_in_any_letter_case() {
        for head in [
            &b"// @generated\nfn f() {}\n"[..],
            b"// @GENERATED\nfn f() {}\n",
            b"  // AUTOMATICALLY GENERATED\nfn f() {}\n",
            b"// Code generated by tool. DO NOT EDIT.\nfn f() {}\n",
            b"# Auto generated by tools/make_width_tables.py\nX = 1\n",
            b"/* Autogenerated */\nint x;\n",
            b"/*\n * auto-generated file\n */\nint x;\n",
            b"(* do not edit *)\nlet x = 1\n",
            b"\"\"\"Autogenerated module.\"\"\"\nX = 1\n",
            b"\xEF\xBB\xBF// @generated\nclass C {}\n",
            b"// GENERATED CODE - DO NOT MODIFY BY HAND\npart of 'a.dart';\n",
        ] {
            assert!(is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn markers_in_code_or_strings_do_not_count() {
        for head in [
            &b"HEADER = \"# Auto generated by this tool\"\n"[..],
            b"const MARKERS: [&str; 1] = [\"do not edit\"];\n",
            b"print('@generated')\n",
            b"// Code generated by hand.\nfn f() {}\n",
            b"fn f() {}\n",
            b"",
        ] {
            assert!(!is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn marker_after_first_code_line_does_not_count() {
        for head in [
            &b"fn f() {}\n// @generated\n"[..],
            b"x = 1\n# auto-generated\n",
            b"package main\n// Code generated by protoc-gen-go. DO NOT EDIT.\n",
            b"<?php\n$x = 1;\n// @generated\n",
            b"// license\nfn f() {}\n// Callers must not edit: do not edit the returned slice\n",
        ] {
            assert!(!is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn marker_in_header_counts() {
        for head in [
            &b"// @generated\nfn f() {}\n"[..],
            b"# auto-generated\nx = 1\n",
            b"/*\nauto-generated file\n*/\nint x;\n",
            b"(*\nauto-generated\n*)\nlet x = 1\n",
            b"\"\"\"\nauto-generated docs\n\"\"\"\nX = 1\n",
            b"<?php\n// @generated\n$x = 1;\n",
            b"\xEF\xBB\xBF# @generated\nx = 1\n",
            b"#!/usr/bin/env python\n# auto-generated\nx = 1\n",
            b"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n",
        ] {
            assert!(is_generated(head), "{}", String::from_utf8_lossy(head));
        }
    }

    #[test]
    fn a_marker_past_the_window_does_not_count() {
        let mut far = b"// ".to_vec();
        far.extend(vec![b'x'; 2048]);
        far.extend_from_slice(b"\n// do not edit\n");
        assert!(!is_generated(&far));
        let mut near = b"// ".to_vec();
        near.extend(vec![b'x'; 1024]);
        near.extend_from_slice(b"\n// do not edit\n");
        assert!(is_generated(&near));
    }

    #[test]
    fn unterminated_block_at_window_end_does_not_panic() {
        let mut open_only = b"/*\n".to_vec();
        open_only.extend(vec![b'x'; 2048]);
        assert!(!is_generated(&open_only));
        let mut open_marker = b"/* do not edit\n".to_vec();
        open_marker.extend(vec![b'x'; 2048]);
        assert!(is_generated(&open_marker));
    }
}
